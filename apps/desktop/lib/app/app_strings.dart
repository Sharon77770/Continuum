  /// Translates a bundled English UI phrase while leaving authored text intact.
  String phrase(String value) {
    final String? key = _phraseKeys[value];
    if (key != null) return text(key);
    final RegExpMatch? httpStatus =
        RegExp(r'^The language model endpoint returned HTTP (\d+)\.$')
            .firstMatch(value);
    if (httpStatus != null) {
      return text('http_status').replaceAll('{status}', httpStatus[1]!);
    }
    final RegExpMatch? readyModel =
        RegExp(r'^(.+) is ready to use\.$').firstMatch(value);
    if (readyModel != null) {
      return text('model_ready').replaceAll('{name}', readyModel[1]!);
    }
    return value;
  }

